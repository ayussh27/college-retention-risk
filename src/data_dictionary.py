"""Write docs/data_dictionary.{csv,md} for the target and every model input.

Run from the project root (after src.clean):  python -m src.data_dictionary

Descriptions, sources and cohort years come from the official Scorecard data
dictionary (docs/reference); missingness and ranges are computed on the
1,737-institution analysis cohort.
"""
import pandas as pd

from src import config as C
from src.features import load_cohort

# Facts the official descriptions leave implicit, checked against the data.
NOTES = {
    "RET_FT4": "Target. Share of the entering cohort still enrolled the next fall.",
    "ADM_RATE": "Missing mostly for open-admission schools.",
    "SAT_AVG": "Missing for test-optional and open-admission schools.",
    "AVGFACSAL": "Dollars per MONTH, not per year.",
    "PAR_ED_PCT_1STGEN": "Discontinued; values are from 2015-17 FAFSA filers and "
                         "'PrivacySuppressed' for small schools (set to NaN).",
    "UGDS": "Log-transformed for linear/SVM models.",
    "TUITFTE": "Log-transformed for linear/SVM models.",
    "INEXPFTE": "Log-transformed for linear/SVM models.",
    "LOCALE_TYPE": "Derived: first digit of LOCALE (1 City, 2 Suburb, 3 Town, 4 Rural).",
    "HBCU": "1 = Historically Black College or University.",
}
DERIVED = {"LOCALE_TYPE": ("Locale type (derived from LOCALE)", "LOCALE")}


def official_entries() -> pd.DataFrame:
    dd = pd.read_excel(C.DICT_XLSX, "Institution_Data_Dictionary")
    dd = dd[dd["VARIABLE NAME"].notna()].drop_duplicates("VARIABLE NAME")
    dd = dd.set_index("VARIABLE NAME")[["NAME OF DATA ELEMENT", "SOURCE"]]
    cm = pd.read_excel(C.DICT_XLSX, "Most_Recent_Inst_Cohort_Map")
    cm = cm.set_index("variable").iloc[:, 0].rename("cohort")
    return dd.join(cm)


def value_labels(var: str) -> str:
    if var == "CONTROL":
        return "; ".join(f"{k} {v}" for k, v in C.CONTROL_LABELS.items())
    if var == "LOCALE_TYPE":
        return "; ".join(f"{k} {v}" for k, v in C.LOCALE_TYPE_LABELS.items())
    if var == "REGION":
        return "0 US service schools; 1 New England ... 8 Far West; 9 Outlying areas"
    return ""


def build() -> pd.DataFrame:
    official = official_entries()
    cohort = load_cohort()
    group_of = {c: g for g, cols in C.FEATURE_GROUPS.items() for c in cols}
    rows = []
    for var in [C.TARGET] + C.FEATURES:
        source_var = DERIVED.get(var, (None, var))[1]
        entry = official.loc[source_var]
        s = cohort[var]
        numeric = var not in C.CATEGORICAL
        rows.append({
            "variable": var,
            "role": "target" if var == C.TARGET else "feature",
            "group": group_of.get(var, "target"),
            "description": DERIVED.get(var, (str(entry["NAME OF DATA ELEMENT"]).split("\n")[0],))[0],
            "type": "numeric" if numeric else "categorical (one-hot)",
            "source": entry["SOURCE"],
            "cohort / period (most-recent file)": entry["cohort"],
            "missing %": round(100 * s.isna().mean(), 1),
            "min": round(s.min(), 4) if numeric else "",
            "median": round(s.median(), 4) if numeric else "",
            "max": round(s.max(), 4) if numeric else "",
            "values": value_labels(var),
            "sensitive (E2)": "yes" if var in C.SENSITIVE else "",
            "notes": NOTES.get(var, ""),
        })
    return pd.DataFrame(rows)


def to_markdown(df: pd.DataFrame) -> str:
    cols = ["variable", "group", "description", "cohort / period (most-recent file)",
            "missing %", "min", "median", "max", "notes"]
    lines = ["# Data dictionary", "",
             "Generated by `python -m src.data_dictionary`. Statistics are computed on the "
             f"{len(load_cohort()):,}-institution analysis cohort (train + test, before imputation). "
             "Descriptions and cohort periods come from the official College Scorecard data "
             "dictionary released October 15, 2026 (`docs/reference/`). Full table with "
             "sources and value labels: `docs/data_dictionary.csv`.", "",
             "| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(str(r[c]).replace("|", "/") for c in cols) + " |")
    return "\n".join(lines) + "\n"


def main() -> None:
    df = build()
    out = C.ROOT / "docs"
    df.to_csv(out / "data_dictionary.csv", index=False)
    (out / "data_dictionary.md").write_text(to_markdown(df), encoding="utf-8")
    print(df[["variable", "group", "missing %", "cohort / period (most-recent file)"]].to_string(index=False))


if __name__ == "__main__":
    main()
